CREATE DATABASE IF NOT EXISTS `ojterm` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `ojterm`;

-- 1. USER
CREATE TABLE IF NOT EXISTS `USER` (
  `UserID` INT AUTO_INCREMENT PRIMARY KEY,
  `Name` VARCHAR(150) NOT NULL,
  `Email` VARCHAR(150) NOT NULL UNIQUE,
  `PasswordHash` VARCHAR(255) NOT NULL,
  `Role` ENUM('Student', 'IndustryPartner', 'OJTCoordinator', 'SchoolAdministrator') NOT NULL,
  `Status` ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_user_email` (`Email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. STUDENT_PROFILE
CREATE TABLE IF NOT EXISTS `STUDENT_PROFILE` (
  `ProfileID` INT AUTO_INCREMENT PRIMARY KEY,
  `UserID` INT NOT NULL UNIQUE,
  `AcademicProgram` VARCHAR(100) NOT NULL,
  `YearLevel` VARCHAR(50) NOT NULL,
  `Interests` TEXT NULL,
  `PreferredLocation` VARCHAR(150) NOT NULL,
  `ResumePath` VARCHAR(255) NULL,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_student_academic_program` (`AcademicProgram`),
  CONSTRAINT `fk_student_profile_user` FOREIGN KEY (`UserID`) REFERENCES `USER` (`UserID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. COMPANY_PROFILE
CREATE TABLE IF NOT EXISTS `COMPANY_PROFILE` (
  `CompanyID` INT AUTO_INCREMENT PRIMARY KEY,
  `UserID` INT NOT NULL UNIQUE,
  `CompanyName` VARCHAR(200) NOT NULL,
  `Industry` VARCHAR(150) NOT NULL,
  `OfficeAddress` VARCHAR(255) NOT NULL,
  `ContactPerson` VARCHAR(150) NOT NULL,
  `ContactEmail` VARCHAR(150) NOT NULL,
  `VerificationStatus` ENUM('Pending', 'Verified', 'Rejected') NOT NULL DEFAULT 'Pending',
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_company_profile_user` FOREIGN KEY (`UserID`) REFERENCES `USER` (`UserID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. SKILL
CREATE TABLE IF NOT EXISTS `SKILL` (
  `SkillID` INT AUTO_INCREMENT PRIMARY KEY,
  `SkillName` VARCHAR(100) NOT NULL UNIQUE,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_skill_name` (`SkillName`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. STUDENT_SKILL (junction)
CREATE TABLE IF NOT EXISTS `STUDENT_SKILL` (
  `ProfileID` INT NOT NULL,
  `SkillID` INT NOT NULL,
  PRIMARY KEY (`ProfileID`, `SkillID`),
  CONSTRAINT `fk_studentskill_profile` FOREIGN KEY (`ProfileID`) REFERENCES `STUDENT_PROFILE` (`ProfileID`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_studentskill_skill` FOREIGN KEY (`SkillID`) REFERENCES `SKILL` (`SkillID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. INTERNSHIP_POSTING
CREATE TABLE IF NOT EXISTS `INTERNSHIP_POSTING` (
  `PostingID` INT AUTO_INCREMENT PRIMARY KEY,
  `CompanyID` INT NOT NULL,
  `Title` VARCHAR(200) NOT NULL,
  `Description` TEXT NOT NULL,
  `Slots` INT NOT NULL,
  `RequiredProgram` VARCHAR(100) NOT NULL,
  `Location` VARCHAR(150) NOT NULL,
  `ApplicationDeadline` DATE NOT NULL,
  `Status` ENUM('Active', 'Closed', 'Draft') NOT NULL DEFAULT 'Active',
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_posting_status` (`Status`),
  INDEX `idx_posting_required_program` (`RequiredProgram`),
  CONSTRAINT `fk_posting_company` FOREIGN KEY (`CompanyID`) REFERENCES `COMPANY_PROFILE` (`CompanyID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 7. POSTING_SKILL_REQUIREMENT (junction)
CREATE TABLE IF NOT EXISTS `POSTING_SKILL_REQUIREMENT` (
  `PostingID` INT NOT NULL,
  `SkillID` INT NOT NULL,
  PRIMARY KEY (`PostingID`, `SkillID`),
  CONSTRAINT `fk_postingskill_posting` FOREIGN KEY (`PostingID`) REFERENCES `INTERNSHIP_POSTING` (`PostingID`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_postingskill_skill` FOREIGN KEY (`SkillID`) REFERENCES `SKILL` (`SkillID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 8. APPLICATION
CREATE TABLE IF NOT EXISTS `APPLICATION` (
  `ApplicationID` INT AUTO_INCREMENT PRIMARY KEY,
  `ProfileID` INT NOT NULL,
  `PostingID` INT NOT NULL,
  `Status` ENUM('Pending', 'Approved', 'Rejected', 'ReturnedForCorrection', 'Placed', 'RejectedByPartner') NOT NULL DEFAULT 'Pending',
  `DateSubmitted` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `DateReviewed` DATETIME NULL,
  `ReviewedByCoordinatorID` INT NULL,
  `PartnerDecision` ENUM('None', 'Accepted', 'Rejected') NOT NULL DEFAULT 'None',
  `FeedbackComment` TEXT NULL,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY `uq_application_student_posting` (`ProfileID`, `PostingID`),
  INDEX `idx_application_status` (`Status`),
  INDEX `idx_application_posting` (`PostingID`),
  INDEX `idx_application_profile` (`ProfileID`),
  CONSTRAINT `fk_application_profile` FOREIGN KEY (`ProfileID`) REFERENCES `STUDENT_PROFILE` (`ProfileID`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_application_posting` FOREIGN KEY (`PostingID`) REFERENCES `INTERNSHIP_POSTING` (`PostingID`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_application_reviewer` FOREIGN KEY (`ReviewedByCoordinatorID`) REFERENCES `USER` (`UserID`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 9. ENDORSEMENT_DOCUMENT
CREATE TABLE IF NOT EXISTS `ENDORSEMENT_DOCUMENT` (
  `DocumentID` INT AUTO_INCREMENT PRIMARY KEY,
  `ApplicationID` INT NOT NULL UNIQUE,
  `FileName` VARCHAR(255) NOT NULL,
  `FilePath` VARCHAR(500) NOT NULL,
  `FileSize` INT NOT NULL,
  `UploadDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_document_application` FOREIGN KEY (`ApplicationID`) REFERENCES `APPLICATION` (`ApplicationID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 10. NOTIFICATION
CREATE TABLE IF NOT EXISTS `NOTIFICATION` (
  `NotificationID` INT AUTO_INCREMENT PRIMARY KEY,
  `UserID` INT NOT NULL,
  `Message` TEXT NOT NULL,
  `Type` ENUM('info', 'success', 'warning', 'error') NOT NULL DEFAULT 'info',
  `DateSent` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `IsRead` BOOLEAN NOT NULL DEFAULT FALSE,
  `RelatedApplicationID` INT NULL,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_notification_user` (`UserID`),
  CONSTRAINT `fk_notification_user` FOREIGN KEY (`UserID`) REFERENCES `USER` (`UserID`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_notification_application` FOREIGN KEY (`RelatedApplicationID`) REFERENCES `APPLICATION` (`ApplicationID`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 11. PLACEMENT_REPORT
CREATE TABLE IF NOT EXISTS `PLACEMENT_REPORT` (
  `ReportID` INT AUTO_INCREMENT PRIMARY KEY,
  `CoordinatorID` INT NOT NULL,
  `Month` INT NOT NULL,
  `Year` INT NOT NULL,
  `GeneratedDate` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `ReportData` JSON NOT NULL,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_report_coordinator` FOREIGN KEY (`CoordinatorID`) REFERENCES `USER` (`UserID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 12. AUDIT_LOG
CREATE TABLE IF NOT EXISTS `AUDIT_LOG` (
  `AuditID` INT AUTO_INCREMENT PRIMARY KEY,
  `UserID` INT NULL,
  `Action` VARCHAR(150) NOT NULL,
  `EntityAffected` VARCHAR(100) NOT NULL,
  `EntityID` VARCHAR(100) NULL,
  `OldValue` JSON NULL,
  `NewValue` JSON NULL,
  `Timestamp` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_audit_user` (`UserID`),
  INDEX `idx_audit_action` (`Action`),
  CONSTRAINT `fk_audit_user` FOREIGN KEY (`UserID`) REFERENCES `USER` (`UserID`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
